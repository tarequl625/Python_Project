# -------------------------------
# Binary to Decimal Conversion
# -------------------------------

# Take binary number input as string
binary = input("Enter a binary number : ")

# Convert binary (base 2) to decimal using int()
decimal = int(binary, 2)

# Print result
print(f"{binary} Binary = {decimal} Decimal")

# -------------------------------
# Example Run - 1:
# Input : 1010
# Output: 1010 Binary = 10 Decimal
#
# Example Run - 2:
# Input : 1111
# Output: 1111 Binary = 15 Decimal
