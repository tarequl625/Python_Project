# -------------------------------
# Kilometers to Miles Conversion
# -------------------------------

# Take kilometers input from user
kilometers = float(input("Enter Kilometers value : "))

# Convert kilometers to miles (1 km = 0.621371 mile)
miles = kilometers * 0.621371

# Print result with 2 decimal precision
print(f"{kilometers} Kilometer = {miles:.2f} Mile")

# -------------------------------
# Example Run - 1:
# Input : 10
# Output: 10.0 Kilometer = 6.21 Mile
#
# Example Run - 2:
# Input : 25
# Output: 25.0 Kilometer = 15.53 Mile
