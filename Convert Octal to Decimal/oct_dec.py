# -------------------------------
# Octal to Decimal Conversion
# -------------------------------

# Take octal number input as string
octal = input("Enter an octal number : ")

# Convert octal (base 8) to decimal
decimal = int(octal, 8)

# Print result
print(f"{octal} Octal = {decimal} Decimal")

# -------------------------------
# Example Run - 1:
# Input : 12
# Output: 12 Octal = 10 Decimal
#
# Example Run - 2:
# Input : 77
# Output: 77 Octal = 63 Decimal
