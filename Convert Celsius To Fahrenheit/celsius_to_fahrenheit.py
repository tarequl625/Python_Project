# -------------------------------
# Celsius to Fahrenheit Conversion
# -------------------------------

# Take Celsius input from user
celsius = float(input("Enter Celsius value : "))

# Convert Celsius to Fahrenheit
fahrenheit = ((celsius * 9) / 5) + 32

# Print result
print(f"{celsius} Celsius = {fahrenheit} Fahrenheit")

