# -------------------------------
# Hexadecimal to Decimal Conversion
# -------------------------------

# Take hexadecimal input from user
hexadecimal = input("Enter a hexadecimal number : ")

# Convert hexadecimal (base 16) to decimal
decimal = int(hexadecimal, 16)

# Print result
print(f"{hexadecimal} Hexadecimal = {decimal} Decimal")

# -------------------------------
# Example Run - 1:
# Input : A
# Output: A Hexadecimal = 10 Decimal
#
# Example Run - 2:
# Input : 1F
# Output: 1F Hexadecimal = 31 Decimal
